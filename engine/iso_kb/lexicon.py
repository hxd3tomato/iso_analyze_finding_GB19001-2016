_COMPILED = [(re.compile(p), c, w, n) for p, c, w, n in PRIOR_RULES]


def prior_scores(text: str) -> dict:
    """返回 {条款: 先验分 0~1}，同一条款取最大权重。"""
    out: dict = {}
    for rx, clause, weight, _ in _COMPILED:
        if rx.search(text):
            if weight > out.get(clause, 0.0):
                out[clause] = weight
    return out


def prior_reasons(text: str, clause: str) -> list:
    return [n for rx, c, w, n in _COMPILED if c == clause and rx.search(text)]


