def route_change(text: str) -> tuple:
    """识别到"变更"类语义时，返回 (条款, 理由)；无法路由返回 (None, None)。"""
    if not re.search(r"变更|更改|改动|换版|改图|ECN", text):
        return None, None
    for rx, clause, label in CHANGE_ROUTES:
        if re.search(rx, text):
            return clause, label
    return None, None


